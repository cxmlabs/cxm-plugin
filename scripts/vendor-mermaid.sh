#!/usr/bin/env bash
# Rebuild src/vendor/mermaid-ascii.js: the text-diagram renderer of beautiful-mermaid, in one
# dependency-free file. A marketplace install runs no `npm install`, so the plugin ships the file.
set -euo pipefail
VERSION=1.1.3
ESBUILD=0.25.10
root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
(cd "$work" && npm pack --silent "beautiful-mermaid@$VERSION" >/dev/null && tar -xzf "beautiful-mermaid-$VERSION.tgz")
out="$root/src/vendor/mermaid-ascii.js"
{
  echo "// Generated by scripts/vendor-mermaid.sh from beautiful-mermaid $VERSION (src/ascii). Do not edit."
  sed 's|^|// |' "$work/package/LICENSE"
  npx --yes "esbuild@$ESBUILD" "$work/package/src/ascii/index.ts" --bundle --format=esm --platform=neutral \
    --tree-shaking=true --legal-comments=none --log-level=warning
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"
